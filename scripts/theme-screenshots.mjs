import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:4190/lab', { waitUntil: 'networkidle' })
  for (const [category, label] of [['all', '全部'], ['develop', '研发'], ['create', '创作'], ['play', '游戏'], ['learn', '学习']]) {
    await page.getByRole('navigation', { name: '实验分类' }).getByRole('button', { name: label }).click()
    await page.waitForTimeout(1000)
    assert.equal(await page.locator('.lab-page').getAttribute('data-category'), category)
    const color = await page.locator('.lab-page').evaluate(el => getComputedStyle(el).backgroundColor)
    assert.equal(color, 'rgb(33, 31, 28)', `${category} should share the site background`)
    await page.screenshot({ path: `design/lab-theme-${category}.png` })
  }
  const categories = page.getByRole('navigation', { name: '实验分类' })
  const shape = page.locator('.lab-backdrop i').first()
  await categories.getByRole('button', { name: '游戏' }).click()
  await page.waitForTimeout(1000)
  const before = await shape.evaluate(el => getComputedStyle(el).transform)
  await categories.getByRole('button', { name: '全部' }).click()
  await page.waitForTimeout(450)
  const during = await shape.evaluate(el => getComputedStyle(el).transform)
  await page.waitForTimeout(600)
  const after = await shape.evaluate(el => getComputedStyle(el).transform)
  assert.notEqual(during, before, 'shape should move during category change')
  assert.notEqual(during, after, 'shape should ease into its destination')
  await page.setViewportSize({ width: 2048, height: 1155 })
  await page.screenshot({ path: 'design/lab-layout-2048.png' })
  await page.setViewportSize({ width: 1024, height: 768 })
  const categoryBottom = await page.locator('.lab-categories').evaluate(el => el.getBoundingClientRect().bottom)
  assert.ok(categoryBottom <= 768, 'desktop category buttons should fit within a short viewport')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('http://127.0.0.1:4190/shelf', { waitUntil: 'networkidle' })
  await page.screenshot({ path: 'design/shelf-spacing-1440.png' })
  const horizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  assert.equal(horizontalOverflow, false)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:4190/lab?category=create', { waitUntil: 'networkidle' })
  await page.screenshot({ path: 'design/lab-theme-mobile.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.goto('http://127.0.0.1:4190/shelf', { waitUntil: 'networkidle' })
  await page.screenshot({ path: 'design/shelf-spacing-390.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.setViewportSize({ width: 320, height: 640 })
  await page.reload({ waitUntil: 'domcontentloaded' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, [])
  console.log('Lab dark themes, category switching, and shelf spacing passed.')
} finally { await browser.close() }
