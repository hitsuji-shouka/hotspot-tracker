export type ShelfCategory = 'movie' | 'book' | 'music'

/** 影视分类下的子分组：动漫 / 剧集 / 电影 */
export type MovieSubgroup = 'anime' | 'series' | 'film'

export interface ShelfItem {
  id: string
  category: ShelfCategory
  subgroup?: MovieSubgroup // 仅 category 为 movie 时有意义
  title: string
  creator: string
  cover?: string
  videoUrl?: string // 配上即为「视频」作品，卡片出现播放标签
  musicUrl?: string // Spotify 链接（track/album/playlist 均可）或网易云歌曲链接，配上后卡片出现「♪ 试听」标签，页面内播放
  note?: string
  rating?: number // 1-5
}

